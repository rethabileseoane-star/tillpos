-- Till POS: seller-controlled subscription and device allow-list.
--
-- Run this once in the Supabase project that hosts licence admin. It is safe to
-- run again. The shop's sync tables are separate; a customer can keep their own
-- Supabase project for shop sync without touching these tables.
--
-- The app never sees the service-role key. Activation and heartbeat go through
-- the `license` Edge Function, which uses that key internally. The admin screen
-- uses a normal Supabase Auth user listed in `license_admins`.
--
-- After running this file:
--   1. Create an Auth user for the seller (Authentication -> Users).
--   2. Insert that user's id into license_admins (SQL below).
--   3. Deploy the license Edge Function and set its signing-key secrets.
--
-- gen_random_uuid() is in core Postgres 13+, so no extension is required.

-- ---------------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------------

create table if not exists public.license_admins (
  user_id    uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.licenses (
  id             uuid primary key default gen_random_uuid(),
  -- SHA-256 of the canonical key (letters/digits only). The key itself is never
  -- stored and is shown once when it is created.
  key_hash       text not null unique,
  business_name  text not null,
  customer_name  text,
  status         text not null default 'active'
                 check (status in ('active', 'suspended')),
  max_devices    integer not null default 1
                 check (max_devices between 1 and 50),
  max_shops      integer not null default 1
                 check (max_shops between 1 and 20),
  offline_hours  integer not null default 24
                 check (offline_hours between 1 and 720),
  expires_at     timestamptz not null,
  notes          text,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);

create table if not exists public.license_devices (
  id            uuid primary key default gen_random_uuid(),
  license_id    uuid not null references public.licenses (id) on delete cascade,
  device_code   text not null,
  label         text,
  status        text not null default 'active'
                check (status in ('active', 'revoked')),
  created_at    timestamptz not null default now(),
  activated_at  timestamptz,
  last_seen_at  timestamptz,
  revoked_at    timestamptz,
  unique (license_id, device_code)
);

create table if not exists public.license_events (
  id          bigint generated by default as identity primary key,
  license_id  uuid references public.licenses (id) on delete set null,
  device_code text,
  event       text not null,
  detail      jsonb,
  created_at  timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- Indexes
-- ---------------------------------------------------------------------------

create index if not exists license_devices_license_idx
  on public.license_devices (license_id);

create index if not exists license_devices_code_idx
  on public.license_devices (device_code);

create index if not exists license_events_license_idx
  on public.license_events (license_id, created_at desc);

-- The rate-limit check in the Edge Function filters on device_code and a time
-- window, so it needs its own index. Without this every activation scans the
-- whole audit table.
create index if not exists license_events_device_idx
  on public.license_events (device_code, created_at desc);

create index if not exists licenses_expiry_idx
  on public.licenses (expires_at);

-- ---------------------------------------------------------------------------
-- updated_at
-- ---------------------------------------------------------------------------

create or replace function public.license_touch()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists licenses_touch on public.licenses;
create trigger licenses_touch
  before update on public.licenses
  for each row execute function public.license_touch();

-- ---------------------------------------------------------------------------
-- Admin helper
-- ---------------------------------------------------------------------------
--
-- SECURITY DEFINER is used so the RLS policy on licenses does not have to
-- recursively read license_admins through RLS. The function has no caller-
-- supplied SQL, is stable, and is executable only by authenticated users. It
-- returns false for every non-admin.

create or replace function public.is_license_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.license_admins a
    where a.user_id = (select auth.uid())
  );
$$;

revoke all on function public.is_license_admin() from public;
revoke all on function public.is_license_admin() from anon;
grant execute on function public.is_license_admin() to authenticated;

-- ---------------------------------------------------------------------------
-- RLS
-- ---------------------------------------------------------------------------

alter table public.license_admins enable row level security;
alter table public.licenses enable row level security;
alter table public.license_devices enable row level security;
alter table public.license_events enable row level security;

drop policy if exists "admins can see themselves" on public.license_admins;
create policy "admins can see themselves"
  on public.license_admins
  for select
  to authenticated
  using (user_id = (select auth.uid()));

drop policy if exists "licence admins manage licences" on public.licenses;
create policy "licence admins manage licences"
  on public.licenses
  for all
  to authenticated
  using (public.is_license_admin())
  with check (public.is_license_admin());

drop policy if exists "licence admins manage devices" on public.license_devices;
create policy "licence admins manage devices"
  on public.license_devices
  for all
  to authenticated
  using (public.is_license_admin())
  with check (public.is_license_admin());

drop policy if exists "licence admins read events" on public.license_events;
create policy "licence admins read events"
  on public.license_events
  for select
  to authenticated
  using (public.is_license_admin());

-- ---------------------------------------------------------------------------
-- Grants: no anon access. The Edge Function uses the service-role key, which
-- bypasses RLS, so it does not need these grants.
-- ---------------------------------------------------------------------------

revoke all on public.license_admins from anon;
revoke all on public.licenses from anon;
revoke all on public.license_devices from anon;
revoke all on public.license_events from anon;

grant select on public.license_admins to authenticated;
grant select, insert, update, delete on public.licenses to authenticated;
grant select, insert, update, delete on public.license_devices to authenticated;
grant select on public.license_events to authenticated;

