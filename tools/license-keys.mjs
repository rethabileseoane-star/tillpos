/**
 * Generate the signing key for the licence server.
 *
 * Run once:
 *   node tools/license-keys.mjs --write
 *
 * It writes:
 *   .license-keys.local.json          private + public JWK (gitignored)
 *   src/licensing/publicKey.generated.ts   public JWK only (safe to commit)
 *
 * Keep .license-keys.local.json off the repository and off customer devices.
 * Put its `privateJwk` value in the Supabase Edge Function secret
 * LICENSE_PRIVATE_JWK and `publicJwk` in LICENSE_PUBLIC_JWK.
 */
import { webcrypto } from 'node:crypto'
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const write = process.argv.includes('--write')
const quiet = process.argv.includes('--quiet')

function b64url(bytes) {
  return Buffer.from(bytes)
    .toString('base64')
    .replace(/\+/g, '-')
    .replace(/\//g, '_')
    .replace(/=+$/g, '')
}

if (!globalThis.crypto) globalThis.crypto = webcrypto

const pair = await crypto.subtle.generateKey(
  { name: 'ECDSA', namedCurve: 'P-256' },
  true,
  ['sign', 'verify'],
)

const privateJwk = await crypto.subtle.exportKey('jwk', pair.privateKey)
const publicJwk = await crypto.subtle.exportKey('jwk', pair.publicKey)

// Keep the export tidy and make the intended use explicit.
privateJwk.alg = 'ES256'
privateJwk.use = 'sig'
privateJwk.key_ops = ['sign']
publicJwk.alg = 'ES256'
publicJwk.use = 'sig'
publicJwk.key_ops = ['verify']

const privateJson = JSON.stringify(privateJwk)
const publicJson = JSON.stringify(publicJwk)

if (write) {
  const root = resolve(fileURLToPath(new URL('..', import.meta.url)))
  const localPath = resolve(root, '.license-keys.local.json')
  const generatedPath = resolve(root, 'src', 'licensing', 'publicKey.generated.ts')

  writeFileSync(
    localPath,
    JSON.stringify(
      {
        note: 'KEEP THIS FILE SECRET. It signs licence tokens. Do not commit or ship it.',
        issuer: 'till-license',
        privateJwk,
        publicJwk,
        env: {
          LICENSE_PRIVATE_JWK: privateJson,
          LICENSE_PUBLIC_JWK: publicJson,
        },
      },
      null,
      2,
    ) + '\n',
    'utf8',
  )

  writeFileSync(
    generatedPath,
    `/** Generated by tools/license-keys.mjs. Public verification key only. */\n` +
      `export const LICENSE_PUBLIC_JWK: JsonWebKey = ${JSON.stringify(publicJwk, null, 2)}\n`,
    'utf8',
  )

  if (!quiet) {
    console.log('Wrote .license-keys.local.json (secret) and src/licensing/publicKey.generated.ts (public).')
    console.log('Next: put the two env values in Supabase Edge Function secrets.')
  }
} else {
  console.log('Private JWK (secret):')
  console.log(privateJson)
  console.log('\nPublic JWK:')
  console.log(publicJson)
  console.log('\nRun with --write to write the local secret and public source file.')
}

// A tiny sanity check so a broken runtime fails loudly instead of writing junk.
const probe = await crypto.subtle.sign(
  { name: 'ECDSA', hash: 'SHA-256' },
  pair.privateKey,
  new TextEncoder().encode('till-licence-key-check'),
)
const ok = await crypto.subtle.verify(
  { name: 'ECDSA', hash: 'SHA-256' },
  pair.publicKey,
  probe,
  new TextEncoder().encode('till-licence-key-check'),
)
if (!ok) throw new Error('Generated key pair failed its sign/verify check.')
if (!quiet) console.log(`Key check passed (${b64url(probe).slice(0, 12)}…).`)
